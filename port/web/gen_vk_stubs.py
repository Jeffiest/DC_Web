#!/usr/bin/env python3
"""Writes a C++ unit defining every Vulkan command declared in vulkan_core.h as a stub that fails.

Browsers have no Vulkan. Until the renderer has a WebGPU backend, the web build links these so the game
and Kazarov's host code compile and link unchanged; vkCreateInstance fails, so the renderer cannot start.

usage: gen_vk_stubs.py <vulkan_core.h> <output.cpp>
"""

import re
import sys

PROTOTYPE = re.compile(r"VKAPI_ATTR\s+(.+?)\s+VKAPI_CALL\s+(vk\w+)\s*\((.*?)\);", re.DOTALL)


def body(return_type: str) -> str:
    return_type = return_type.strip()
    if return_type == "void":
        return "{}"
    if return_type == "VkResult":
        return "{ return VK_ERROR_INITIALIZATION_FAILED; }"
    return "{ return {}; }"


def main() -> int:
    header, output = sys.argv[1], sys.argv[2]
    with open(header, encoding="utf-8") as file:
        text = file.read()
    seen = set()
    lines = [
        "// Generated by port/web/gen_vk_stubs.py: every Vulkan command, failing. Do not edit.",
        "#include <vulkan/vulkan_core.h>",
        "",
        'extern "C" {',
    ]
    for return_type, name, params in PROTOTYPE.findall(text):
        if name in seen:
            continue
        seen.add(name)
        params = " ".join(params.split())
        lines.append(f"VKAPI_ATTR {return_type} VKAPI_CALL {name}({params}) {body(return_type)}")
    lines += ["}", ""]
    with open(output, "w", encoding="utf-8") as file:
        file.write("\n".join(lines))
    print(f"gen_vk_stubs: {len(seen)} commands", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
